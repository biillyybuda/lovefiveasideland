require('./register-typescript.cjs');
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const {buildLeagueRatings,applyLeagueChange,DRAFT_MATCH_ID}=require('../lib/result-rebuild.ts');
const {randomUUID}=require('node:crypto');
const migrations=path.resolve(__dirname,'../../supabase/migrations');
const read=name=>fs.readFileSync(path.join(migrations,name),'utf8');
const admin='00000000-0000-4000-8000-000000000001',member='00000000-0000-4000-8000-000000000002';

test('competition migration and atomic RPC preserve immunity through the full result lifecycle',async t=>{
  const db=await PGlite.create();t.after(()=>db.close());
  // Minimal existing schema, with real roles, policies, old migrations and PL/pgSQL triggers.
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth to authenticated,anon;
    create table leagues(id bigint primary key);
    create table league_members(league_id bigint,user_id uuid,role text,status text);
    create table players(id bigint generated by default as identity primary key,league_id bigint references leagues(id),name text,display_name text,
      mmr float8 default 1000,matches_played integer default 0,wins integer default 0,draws integer default 0,losses integer default 0,
      win_streak integer default 0,lose_streak integer default 0,is_active integer default 1);
    create table matches(id bigint generated by default as identity primary key,league_id bigint references leagues(id),date text,team_a text,team_b text,score text,result text,processed integer);
    create table mmr_history(id bigint generated by default as identity primary key,league_id bigint references leagues(id),player_id bigint references players(id),match_id bigint references matches(id) on delete cascade,date text,mmr_before float8,mmr_after float8);
    alter table players enable row level security;
    create policy players_league_admin_write on players for all to authenticated using(false) with check(false);
    alter table matches enable row level security; alter table mmr_history enable row level security;
    create policy matches_admin on matches for all to authenticated using(exists(select 1 from league_members lm where lm.league_id=matches.league_id and lm.user_id=auth.uid() and lm.role='owner' and lm.status='active'));
    create policy history_admin on mmr_history for all to authenticated using(exists(select 1 from league_members lm where lm.league_id=mmr_history.league_id and lm.user_id=auth.uid() and lm.role='owner' and lm.status='active'));
    grant select on leagues,league_members to authenticated;
    grant select,insert,update,delete on players,matches,mmr_history to authenticated;
    grant usage on all sequences in schema public to authenticated;
    insert into leagues values(1),(2);
    insert into league_members values(1,'${admin}','owner','active'),(1,'${member}','member','active');
    insert into players(league_id,name) select 1,'p'||n from generate_series(1,11) n;
  `);
  await db.exec(read('20260908080902_mmr_v2_foundation.sql'));
  await db.exec(read('20260911073619_match_review_notes.sql'));
  await db.exec(read('20260922074013_mmr_immunity_shield.sql'));
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${admin}',false);`);
  const workspace=async()=> (await db.query('select rating_workspace(1) as data')).rows[0].data;
  const rawCommit=async(w,change,calc,id=randomUUID(),token=w.token)=> (await db.query(
    'select commit_competition_rating_run(1,$1,$2,$3,$4,$5) as data',
    [token,id,JSON.stringify(change),JSON.stringify(calc),'margin-v1'])).rows[0].data;
  const save=async(change)=>{const w=await workspace();const calc=buildLeagueRatings(w,applyLeagueChange(w.matches,change));return rawCommit(w,change,calc);};
  const draft={id:DRAFT_MATCH_ID,date:'2026-09-17',team_a:'p1,p2,p3,p4,p5',team_b:'p6,p7,p8,p9,p10',score:'5-3',result:'A',processed:1,competition:'league',review_note:'Keep this note'};
  assert.equal((await save({action:'add',match:draft})).historyRows,10);
  const league=await workspace();
  const ratingValues=w=>w.history.map(({id,...h})=>h);
  const assertProtected=async()=>{const w=await workspace();assert.deepEqual(w.players,league.players);assert.deepEqual(ratingValues(w),ratingValues(league));};
  const cup={...draft,date:'2026-09-22',score:'8-8',result:'Draw',competition:'immunity_shield'};
  const w=await workspace(),change={action:'add',match:cup},calc=buildLeagueRatings(w,applyLeagueChange(w.matches,change)),requestId=randomUUID();
  const summary=await rawCommit(w,change,calc,requestId);
  assert.deepEqual(summary,{processedMatches:2,ratedMatches:1,playersUpdated:11,historyRows:10});
  await assertProtected();
  assert.deepEqual(await rawCommit(w,change,{},requestId,''),summary,'lost-response retry returns original save');
  assert.equal((await workspace()).matches.length,2);
  await assert.rejects(rawCommit(w,{...change,match:{...cup,score:'8-7'}},{},requestId,''),/Request ID already used/);
  const savedCup=(await workspace()).matches.find(m=>m.competition==='immunity_shield');
  await save({action:'edit',original:savedCup,match:{...savedCup,score:'20-0',date:'2025-01-01'}});
  await assertProtected();
  assert.equal((await workspace()).matches.find(m=>m.id===savedCup.id).review_note,'Keep this note');
  await save({action:'rebuild'});await assertProtected();
  const edited=(await workspace()).matches.find(m=>m.id===savedCup.id);
  await save({action:'edit',original:edited,match:{...edited,competition:'league'}});
  assert.equal((await workspace()).history.length,20);
  await save({action:'edit',original:{...edited,competition:'league'},match:edited});
  await assertProtected();
  const current=await workspace();
  const invalid=buildLeagueRatings(current);invalid.history[0].player_id=11;
  await assert.rejects(rawCommit(current,{action:'rebuild'},invalid),/not a participant/);
  const shieldHistory=buildLeagueRatings(current);shieldHistory.history[0].match_id=savedCup.id;
  await assert.rejects(rawCommit(current,{action:'rebuild'},shieldHistory),/Invalid history reference/);
  await assert.rejects(rawCommit(current,{action:'rebuild'},buildLeagueRatings(current),randomUUID(),'stale'),/League changed/);
  await assert.rejects(db.query('select commit_rating_run(1,$1,$2,$3,$4,$5)',['',randomUUID(),'{}','{}','margin-v1']),/Refresh the website/);
  await db.exec(`select set_config('request.jwt.claim.sub','${member}',false)`);
  await assert.rejects(workspace(),/League admin access required/);
  await db.exec(`select set_config('request.jwt.claim.sub','${admin}',false)`);
  await assert.rejects(db.query('select rating_workspace(2)'),/League admin access required/);
  await save({action:'delete',match:edited});await assertProtected();
  assert.equal((await workspace()).matches.length,1);
  await db.exec('reset role; set role anon;');
  await assert.rejects(db.query('select commit_competition_rating_run(1,$1,$2,$3,$4,$5)',['',randomUUID(),'{}','{}','margin-v1']),/permission denied/);
});
